def slugify(text: str) -> str:
    """Generate a clean URL-friendly slug."""
    import re
    cleaned = re.sub(r"[^a-zA-Z0-9\s-]", "", text.strip().lower())
    return re.sub(r"[\s_-]+", "-", cleaned).strip("-") or "company"
